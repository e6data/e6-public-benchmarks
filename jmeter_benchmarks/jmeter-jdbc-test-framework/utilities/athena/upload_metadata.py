#!/usr/bin/env python3
"""
Upload metadata JSONL files to S3 for jmeter_run_metadata Athena table.

This script uploads partitioned JSONL files generated by generate_metadata_index.py
to the Athena table location in S3.

Usage:
    # Upload from default location
    python utilities/athena/upload_metadata.py /tmp/metadata/

    # Upload specific partition
    python utilities/athena/upload_metadata.py /tmp/metadata/ --partition engine=e6data/cluster_size=S-2x2

    # Dry run (no actual upload)
    python utilities/athena/upload_metadata.py /tmp/metadata/ --dry-run
"""

import argparse
import subprocess
import sys
from pathlib import Path
from typing import List, Tuple


def find_metadata_files(base_dir: str) -> List[Tuple[Path, str]]:
    """
    Find all metadata.jsonl files in partitioned directory structure.

    Returns list of (file_path, s3_partition_path) tuples.
    Expected structure: engine=X/cluster_size=Y/metadata.jsonl
    """
    base_path = Path(base_dir)

    if not base_path.exists():
        raise ValueError(f"Directory does not exist: {base_dir}")

    files = []

    # Find all metadata.jsonl files
    for jsonl_file in base_path.rglob("metadata.jsonl"):
        # Extract partition from path
        # Example: /tmp/metadata/engine=e6data/cluster_size=S-2x2/metadata.jsonl
        relative_path = jsonl_file.relative_to(base_path)
        partition_path = str(relative_path.parent)  # e.g., "engine=e6data/cluster_size=S-2x2"

        files.append((jsonl_file, partition_path))

    return sorted(files, key=lambda x: x[1])


def upload_to_s3(local_file: Path, s3_partition_path: str, s3_bucket: str,
                 s3_prefix: str, dry_run: bool = False) -> bool:
    """
    Upload JSONL file to S3 at the correct partition path.

    Args:
        local_file: Local JSONL file path
        s3_partition_path: Partition path (e.g., "engine=e6data/cluster_size=S-2x2")
        s3_bucket: S3 bucket name
        s3_prefix: S3 prefix (e.g., "athena-tables/run_metadata")
        dry_run: If True, print command but don't execute

    Returns:
        True if successful, False otherwise
    """
    # Build S3 destination
    s3_path = f"s3://{s3_bucket}/{s3_prefix}/{s3_partition_path}/metadata.jsonl"

    cmd = ['aws', 's3', 'cp', str(local_file), s3_path]

    if dry_run:
        print(f"[DRY RUN] Would upload: {local_file} -> {s3_path}")
        return True

    try:
        result = subprocess.run(cmd, capture_output=True, text=True, check=True)
        return True
    except subprocess.CalledProcessError as e:
        print(f"❌ Upload failed: {e.stderr}")
        return False


def repair_partitions(database: str = 'default', dry_run: bool = False) -> bool:
    """
    Run MSCK REPAIR TABLE to discover new partitions in Athena.

    Args:
        database: Athena database name
        dry_run: If True, print command but don't execute

    Returns:
        True if successful, False otherwise
    """
    query = "MSCK REPAIR TABLE jmeter_run_metadata"

    cmd = [
        'aws', 'athena', 'start-query-execution',
        '--query-string', query,
        '--query-execution-context', f'Database={database}',
        '--result-configuration', 'OutputLocation=s3://e6-jmeter/athena-query-results/',
        '--output', 'text',
        '--query', 'QueryExecutionId'
    ]

    if dry_run:
        print(f"[DRY RUN] Would repair partitions: {query}")
        return True

    try:
        result = subprocess.run(cmd, capture_output=True, text=True, check=True)
        query_id = result.stdout.strip()
        print(f"✓ Partition repair query submitted: {query_id}")
        return True
    except subprocess.CalledProcessError as e:
        print(f"❌ Partition repair failed: {e.stderr}")
        return False


def main():
    parser = argparse.ArgumentParser(
        description='Upload metadata JSONL files to S3 for Athena ingestion',
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__
    )

    parser.add_argument(
        'metadata_dir',
        help='Local directory containing partitioned metadata JSONL files'
    )

    parser.add_argument(
        '--bucket', '-b',
        help='S3 bucket name (default: e6-jmeter)',
        default='e6-jmeter'
    )

    parser.add_argument(
        '--prefix', '-p',
        help='S3 prefix (default: athena-tables/run_metadata)',
        default='athena-tables/run_metadata'
    )

    parser.add_argument(
        '--database', '-d',
        help='Athena database name (default: default)',
        default='default'
    )

    parser.add_argument(
        '--partition',
        help='Upload specific partition only (e.g., engine=e6data/cluster_size=S-2x2)',
        default=None
    )

    parser.add_argument(
        '--dry-run',
        action='store_true',
        help='Print commands without executing'
    )

    parser.add_argument(
        '--skip-repair',
        action='store_true',
        help='Skip MSCK REPAIR TABLE after upload'
    )

    args = parser.parse_args()

    # Find all metadata files
    try:
        files = find_metadata_files(args.metadata_dir)
    except ValueError as e:
        print(f"❌ {e}")
        sys.exit(1)

    if not files:
        print(f"❌ No metadata.jsonl files found in {args.metadata_dir}")
        print(f"   Expected structure: engine=X/cluster_size=Y/metadata.jsonl")
        sys.exit(1)

    # Filter by partition if specified
    if args.partition:
        files = [(f, p) for f, p in files if p == args.partition]
        if not files:
            print(f"❌ No files found for partition: {args.partition}")
            sys.exit(1)

    print("=" * 70)
    print("📤 METADATA UPLOAD TO S3")
    print("=" * 70)
    print(f"Source directory: {args.metadata_dir}")
    print(f"S3 destination: s3://{args.bucket}/{args.prefix}/")
    print(f"Files to upload: {len(files)}")
    if args.dry_run:
        print("Mode: DRY RUN (no actual uploads)")
    print("=" * 70)
    print()

    # Upload each file
    uploaded = 0
    failed = 0

    for local_file, partition_path in files:
        print(f"📁 Partition: {partition_path}")
        print(f"   File: {local_file}")

        # Count records in file
        with open(local_file) as f:
            record_count = sum(1 for _ in f)
        print(f"   Records: {record_count}")

        # Upload
        if upload_to_s3(local_file, partition_path, args.bucket, args.prefix, args.dry_run):
            print(f"   ✅ Uploaded successfully")
            uploaded += 1
        else:
            failed += 1

        print()

    # Summary
    print("=" * 70)
    print("📊 UPLOAD SUMMARY")
    print("=" * 70)
    print(f"Total files: {len(files)}")
    print(f"Uploaded: {uploaded}")
    print(f"Failed: {failed}")
    print("=" * 70)
    print()

    if failed > 0:
        print("❌ Some uploads failed. Check errors above.")
        sys.exit(1)

    # Repair partitions
    if not args.skip_repair and not args.dry_run:
        print("🔧 Repairing Athena table partitions...")
        if repair_partitions(args.database, args.dry_run):
            print("✅ Partitions repaired successfully")
        else:
            print("⚠️  Partition repair failed, but uploads succeeded")
            print("   You can manually repair with:")
            print(f"   MSCK REPAIR TABLE {args.database}.jmeter_run_metadata;")

    print()
    print("=" * 70)
    print("✅ METADATA UPLOAD COMPLETE!")
    print("=" * 70)
    print()
    print("Next steps:")
    print("1. Verify data in Athena:")
    print(f"   SELECT COUNT(*) FROM {args.database}.jmeter_run_metadata;")
    print()
    print("2. Check partition discovery:")
    print(f"   SHOW PARTITIONS {args.database}.jmeter_run_metadata;")
    print()
    print("3. Query results table (uses existing CSV data):")
    print(f"   MSCK REPAIR TABLE {args.database}.jmeter_query_results;")
    print(f"   SELECT COUNT(*) FROM {args.database}.jmeter_query_results;")
    print("=" * 70)


if __name__ == '__main__':
    main()
